"""Pairwise boundary-completion diagnostic for one-dimensional kernels.

The experiment uses the boundary target

    u*(x) = K'''(x) + beta K(x-c0),     K(x)=exp(-x^2/2).

The diagnostic follows the stepwise completion rule described in the paper, but
the plotted trajectories are generated by ordinary full-batch Adam. Starting
from translated atoms, pairs of same-order atoms are collapsed and replaced by a
same-order atom plus the next derivative atom. A stage change is triggered by a
drop in the active pair separation, not by a prescribed iteration count. For a
third derivative target this produces three completion events:

    translated atoms  -> add K'  -> add K''  -> add K'''.

The extra order-zero atom used for the non-derivative part of the target is
initialized away from c0 and its center is trained with Adam.
"""

