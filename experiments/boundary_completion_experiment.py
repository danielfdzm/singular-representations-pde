def plot_representation_evolution(
    result: dict[str, object],
    x_plot: np.ndarray,
    target_plot: np.ndarray,
) -> None:
    mpl.rcParams.update(
        {
            "font.family": "serif",
            "font.serif": ["Latin Modern Roman", "Computer Modern Roman", "DejaVu Serif"],
            "mathtext.fontset": "cm",
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "axes.linewidth": 0.9,
            "xtick.major.width": 0.8,
            "ytick.major.width": 0.8,
            "xtick.major.size": 3.4,
            "ytick.major.size": 3.4,
            "xtick.labelsize": 8.0,
            "ytick.labelsize": 8.0,
            "axes.labelsize": 8.2,
            "axes.titlesize": 8.6,
            "legend.fontsize": 8.0,
        }
    )

    order_colors = {
        0: "#0000FF",
        1: "#D55E00",
        2: "#7B3294",
        3: "#188038",
    }
    order_markers = {0: "o", 1: "s", 2: "^", 3: "D"}
    order_linestyles = {0: "-", 1: "--", 2: "-.", 3: ":"}
    sum_color = "#0000FF"
    target_color = "#111111"
    ordinary_color = "#E69F00"
    band_color = "#F1F1F1"
    gray = "#6A6A6A"

    fig = plt.figure(figsize=(4.685, 6.65))
    gs = fig.add_gridspec(
        6,
        2,
        height_ratios=(0.92, 1.35, 1.18, 0.92, 1.35, 1.18),
        left=0.14,
        right=0.980,
        bottom=0.070,
        top=0.955,
        wspace=0.28,
        hspace=0.66,
    )
    axes = np.asarray([[fig.add_subplot(gs[row, col]) for col in range(2)] for row in range(6)])

    summaries = result["summaries"]
    y_span = float(np.max(np.abs(target_plot)))
    bottom_lim = 1.16 * max(y_span, 1e-12)
    top_stage_notes = (
        r"$8$ initial atoms",
        r"$4$ collapsing $K'$ atoms",
        r"$2$ collapsing $K''$ atoms",
        r"explicit $K'''$ atom",
    )
    stage_iterations = np.asarray(result["iteration"], dtype=float)
    stage_ids = np.asarray(result["stage"], dtype=int)
    stage_errors = np.asarray(result["relative_error"], dtype=float)
    event_iterations = [float(value) for value in result["event_iterations"]]
    n_ordinary = len(result.get("ordinary_initial_centers", [PRIMARY_INITIAL_CENTER]))

    def is_ordinary_index(index: int, n_atoms: int) -> bool:
        return index >= n_atoms - n_ordinary

    def schematic_x(atom: Atom, stage: int, cluster_scale: float, is_ordinary: bool) -> float:
        if is_ordinary:
            return 1.04
        if stage == 3:
            return 0.055 * (atom.order - 1.5)
        base = 0.62 * atom.center / cluster_scale if cluster_scale > 0.0 else 0.0
        return base + 0.028 * (atom.order - 0.5 * stage)

    def draw_architecture_panel(
        ax: plt.Axes,
        atoms: list[Atom],
        weights: np.ndarray,
        stage: int,
    ) -> None:
        n_atoms = len(atoms)
        cluster_centers = [abs(atom.center) for index, atom in enumerate(atoms) if not is_ordinary_index(index, n_atoms)]
        cluster_scale = max(cluster_centers) if cluster_centers else 1.0
        max_log_weight = max(float(np.max(np.log1p(np.abs(weights)))), 1e-12)
        node_x: list[float] = []
        node_order: list[int] = []

        ax.axhline(0.0, color="#CFCFCF", lw=0.75, zorder=0)
        for index, (atom, weight) in enumerate(zip(atoms, weights)):
            ordinary_atom = is_ordinary_index(index, n_atoms)
            x_node = schematic_x(atom, stage, cluster_scale, ordinary_atom)
            signed = np.sign(weight) if abs(weight) > 1e-14 else 1.0
            height = signed * (0.22 + 0.55 * np.log1p(abs(weight)) / max_log_weight)
            color = ordinary_color if ordinary_atom else order_colors.get(atom.order, "#555555")
            alpha = 0.95 if (ordinary_atom or atom.order == stage) else 0.42
            size = 12.0 + 42.0 * np.log1p(abs(weight)) / max_log_weight
            lw = 0.9 if atom.order == stage or ordinary_atom else 0.65

            ax.plot([x_node, x_node], [0.0, height], color=color, lw=lw, alpha=alpha, solid_capstyle="round")
            ax.scatter(
                [x_node],
                [height],
                s=size,
                marker="*" if ordinary_atom else order_markers.get(atom.order, "o"),
                color=color,
                edgecolor="white",
                linewidth=0.45,
                alpha=alpha,
                zorder=3,
            )
            if not ordinary_atom:
                node_x.append(x_node)
                node_order.append(atom.order)

        ax.set_xlim(-0.78, 1.22)
        ax.set_ylim(-1.0, 1.02)
        ax.set_xticks([])
        ax.set_yticks([])
        for spine in ax.spines.values():
            spine.set_visible(False)

    for stage in range(4):
        block_row = 3 * (stage // 2)
        col = stage % 2
        summary = summaries[f"stage_{stage}"]
        atoms = [Atom(int(order), float(center)) for order, center in summary["basis"]]
        weights = np.asarray(summary["weights"], dtype=np.float64)
        phi = basis_from_atoms(x_plot, atoms)
        terms = phi * weights[None, :]
        represented = np.sum(terms, axis=1)

        ax_arch = axes[block_row, col]
        draw_architecture_panel(ax_arch, atoms, weights, stage)
        ax_arch.set_title(STAGE_LABELS[stage] + "\n" + top_stage_notes[stage], pad=3.0, fontsize=8.4)
        if col == 0:
            ax_arch.text(
                -0.12,
                0.5,
                "collapse tree",
                rotation=90,
                va="center",
                ha="center",
                transform=ax_arch.transAxes,
                fontsize=8.2,
            )

        ax_terms = axes[block_row + 1, col]
        ax_terms.axhspan(-bottom_lim, bottom_lim, color=band_color, alpha=0.82, zorder=0)
        ax_terms.axhline(0.0, color="#AFAFAF", lw=0.65, zorder=1)
        labels_used: set[str] = set()
        for atom, term in zip(atoms, terms.T):
            label = rf"$wK^{{({atom.order})}}$"
            color = order_colors.get(atom.order, "#555555")
            lw = 0.9
            alpha = 0.72
            ax_terms.plot(
                x_plot,
                term,
                color=color,
                lw=lw,
                ls=order_linestyles.get(atom.order, "-"),
                alpha=alpha,
                label=label if label not in labels_used else None,
            )
            labels_used.add(label)

        term_lim = 1.08 * max(float(np.max(np.abs(terms))), 1e-12)
        ax_terms.set_ylim(-term_lim, term_lim)
        ax_terms.ticklabel_format(axis="y", style="sci", scilimits=(-2, 2))
        if stage == 3:
            ax_terms.legend(frameon=False, loc="upper right", handlelength=1.35)
        if col == 0:
            ax_terms.set_ylabel("weighted atoms")

        ax_error = axes[block_row + 2, col]
        current_iteration = float(summary["iteration"])
        mask = stage_iterations <= current_iteration
        ax_error.semilogy(stage_iterations[mask], stage_errors[mask], color=sum_color, lw=1.35)
        for event in event_iterations:
            if event <= current_iteration:
                ax_error.axvline(event, color=gray, lw=0.75, ls="--", alpha=0.62)
        ax_error.scatter(
            [current_iteration],
            [float(summary["relative_error"])],
            s=14,
            color=sum_color,
            edgecolor="white",
            linewidth=0.35,
            zorder=3,
        )
        ax_error.set_ylim(1e-16, 1e1)
        ax_error.xaxis.set_major_locator(mpl.ticker.MaxNLocator(4))
        ax_error.xaxis.set_major_formatter(
            mpl.ticker.FuncFormatter(lambda value, _position: f"{value / 1.0e5:g}")
        )
        if block_row == 0:
            ax_error.tick_params(axis="x", labelbottom=False)
        ax_error.text(
            0.96,
            0.08,
            rf"$\mathrm{{err}}={summary['relative_error']:.1e}$" + "\n"
            + rf"$\|w\|_2={summary['weight_norm']:.1e}$",
            transform=ax_error.transAxes,
            ha="right",
            va="bottom",
            fontsize=8.0,
            bbox={"facecolor": "white", "edgecolor": "#DDDDDD", "boxstyle": "round,pad=0.2", "alpha": 0.88},
        )

        ax_terms.set_xlim(-1.35, 2.65)
        ax_error.set_xlim(0.0, float(np.max(stage_iterations)))
        if col == 0:
            ax_error.set_ylabel("relative error")
        for ax in (ax_terms, ax_error):
            ax.grid(False)

    fig.supxlabel(r"iteration ($\times 10^5$)", x=0.56, y=0.016, fontsize=8.2)
    fig.savefig(OUT_REP_PDF)
    fig.savefig(OUT_REP_PNG, dpi=240)
    plt.close(fig)


